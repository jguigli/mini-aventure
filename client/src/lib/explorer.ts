// Reachability explorer: plays every path of a compiled Ink story.
// This is how the app proves that every scene and both endings can be reached.
// It runs on the compiled story (not the JSON), so it also works for imported .ink files.
//
// Algorithm: depth-first search over decision points.
//   1. Run the story until it stops (choices to make, or the end), collecting tags.
//   2. At a decision point: save the state, then for each choice: choose, recurse, restore.
//   3. Loops: a decision point already explored is skipped (see `decisionKey`).
//   4. Safety net: stop after `maxSteps` choices and report `truncated`.
import type { InkStory } from "./inkCompile";
import { tagValue } from "./inkTags";

export interface ExploreOptions {
  /** Maximum number of choices taken in total before giving up. */
  maxSteps?: number;
  /**
   * Every scene that should be reachable, used to compute `unreachedScenes`.
   * Defaults to the story's top-level knots. For an imported .ink, pass
   * `knotNamesFromSource(source)` so functions are not counted as scenes.
   */
  sceneIds?: string[];
}

export interface ExploreResult {
  /** Scenes seen at least once (scene tags, or knots with a visit count). */
  reachedScenes: Set<string>;
  /** "A" / "B" for generated stories; the ending knot's name for an imported .ink. */
  reachedEndings: Set<string>;
  /** Scenes where the story stops without an ending (no choices, missing target, runtime error). */
  deadEnds: string[];
  unreachedScenes: string[];
  /** inkjs runtime errors met while playing (e.g. "ran out of content"). */
  runtimeErrors: string[];
  /** True if `maxSteps` was hit: the results are then incomplete. */
  truncated: boolean;
  /** Number of choices taken. */
  steps: number;
}

export const DEFAULT_MAX_STEPS = 10_000;
/**
 * Maximum depth of the search (choices in a row). The search is recursive: without this
 * guard, an imported .ink with many distinct states could overflow the call stack and
 * crash the page. Beyond it, the exploration stops and reports `truncated`.
 */
export const MAX_DEPTH = 1_000;

/** Name of the knot a path belongs to: "cuisine.placard.0.7" → "cuisine". */
export const knotOf = (path: string) => path.split(".")[0];

/** Top-level knots of a compiled story ("global decl" holds VAR declarations, it is not a knot). */
function knotNames(story: InkStory): string[] {
  return [...story.mainContentContainer.namedContent.keys()].filter(
    (name) => name !== "global decl",
  );
}

/** Knot names declared in Ink source, without functions (`=== function name ===`). */
export function knotNamesFromSource(source: string): string[] {
  const names = [...source.matchAll(/^\s*={2,}\s*(?!function\b)([A-Za-z_]\w*)/gm)].map((m) => m[1]);
  return [...new Set(names)];
}

/**
 * Identifies a decision point by where its choices come from and what they say.
 * We do NOT compare `state.ToJson()`: it contains visit and turn counters that change
 * on every pass, so two visits of the same scene would never look equal and a loop
 * would run until `maxSteps`. For our generated stories (no variables), the same choices
 * always lead to the same places, so this key is exact. For an imported .ink with
 * variables it is an approximation, and `maxSteps` remains the safety net.
 */
function decisionKey(story: InkStory): string {
  return story.currentChoices.map((choice) => `${choice.sourcePath}:${choice.text}`).join("|");
}

/**
 * Explores every path of `story`. The story's state is reset before and after,
 * so do not run it on a story the reader is currently playing.
 */
export function explore(story: InkStory, opts: ExploreOptions = {}): ExploreResult {
  const maxSteps = opts.maxSteps ?? DEFAULT_MAX_STEPS;
  const allScenes = opts.sceneIds ?? knotNames(story);

  const reachedScenes = new Set<string>();
  const reachedEndings = new Set<string>();
  const deadEnds = new Set<string>();
  const runtimeErrors = new Set<string>();
  const explored = new Set<string>();
  let steps = 0;
  let truncated = false;
  // Tagged mode = generated by this app (every scene has `# scene:`). Decided on the first segment.
  let tagged: boolean | null = null;

  const visitCounts = () =>
    new Map(allScenes.map((name) => [name, story.state.VisitCountAtPathString(name) ?? 0]));

  /**
   * Plays one branch from the current state. `fromScene` is the scene where the
   * choice leading here was made (used when this segment has no scene of its own,
   * e.g. a choice whose target is missing).
   */
  function visit(fromScene: string | null, depth: number): void {
    if (depth > MAX_DEPTH) {
      truncated = true;
      return;
    }
    // 1. Run until the next decision point or the end, collecting tags.
    const before = visitCounts();
    const tags: string[] = [];
    let error: string | null = null;
    try {
      while (story.canContinue) {
        story.Continue();
        tags.push(...(story.currentTags ?? []));
      }
    } catch (e) {
      // inkjs throws on runtime errors instead of returning them.
      error = e instanceof Error ? e.message : String(e);
    }

    // 2. Record the scenes reached in this segment.
    const sceneTag = tagValue(tags, "scene");
    if (tagged === null) tagged = sceneTag !== null;
    if (sceneTag) reachedScenes.add(sceneTag);
    const after = visitCounts();
    const newlyVisited = allScenes.filter(
      (name) => (after.get(name) ?? 0) > (before.get(name) ?? 0),
    );
    for (const name of allScenes) if ((after.get(name) ?? 0) > 0) reachedScenes.add(name);

    // The scene this segment belongs to: its tag; else the knot its choices come from;
    // else a knot it entered (for an imported ending); else the scene we came from
    // (a choice with a missing target ends the story without entering any scene).
    const firstChoice = story.currentChoices[0];
    const scene =
      sceneTag ??
      (firstChoice ? knotOf(firstChoice.sourcePath) : null) ??
      newlyVisited.at(-1) ??
      fromScene;

    if (error) {
      runtimeErrors.add(error);
      deadEnds.add(scene ?? "?");
      return;
    }

    // 3. End of the story on this branch: an ending, or a dead end.
    if (story.currentChoices.length === 0) {
      const ending = tagValue(tags, "ending");
      if (ending) reachedEndings.add(ending);
      else if (tagged)
        deadEnds.add(scene ?? "?"); // our stories always tag their endings
      else reachedEndings.add(scene ?? "?"); // imported .ink: any end of the story is an ending
      return;
    }

    // 4. Decision point: skip it if already explored (this is what stops loops).
    const key = decisionKey(story);
    if (explored.has(key)) return;
    explored.add(key);

    // 5. Try every choice from the same saved state.
    const saved = story.state.ToJson();
    const choiceCount = story.currentChoices.length;
    for (let i = 0; i < choiceCount; i++) {
      if (steps >= maxSteps) {
        truncated = true;
        return;
      }
      steps++;
      story.ChooseChoiceIndex(i);
      visit(scene, depth + 1);
      story.state.LoadJson(saved);
    }
  }

  story.ResetState();
  visit(null, 0);
  story.ResetState();

  return {
    reachedScenes,
    reachedEndings,
    deadEnds: [...deadEnds],
    unreachedScenes: allScenes.filter((name) => !reachedScenes.has(name)),
    runtimeErrors: [...runtimeErrors],
    truncated,
    steps,
  };
}
